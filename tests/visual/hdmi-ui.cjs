const { app, BrowserWindow } = require('electron');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
if (!process.env.ASTRELIS_VISUAL_PROFILE || !process.env.ASTRELIS_VISUAL_ORIGIN) throw new Error('Use isolated visual runner');
app.setPath('userData', process.env.ASTRELIS_VISUAL_PROFILE);
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
  await app.whenReady();
  const win = new BrowserWindow({ width: 1280, height: 900, show: false, webPreferences: { offscreen: true, backgroundThrottling: false, contextIsolation: true } });
  win.webContents.setAudioMuted(true);
  const errors = [];
  win.webContents.on('console-message', (_, level, message) => { if (level >= 3 && !message.includes('ERR_')) { errors.push(message); console.error('Renderer:', message); } });
  const evaluate = fn => win.webContents.executeJavaScript(`(async()=>{try{return await (${fn.toString()})()}catch(e){console.error(e.stack);throw e}})()`, true);
  await win.loadURL(process.env.ASTRELIS_VISUAL_ORIGIN);
  await evaluate(async () => {
    const { usePlayerStore } = await import('/src/stores/playerStore.ts');
    window.__hdmi = usePlayerStore;
    window.__allowHdmi = true;
    const device = { backend: 'wasapi-shared', juceTypeName: 'Windows Audio', juceDeviceName: 'HDMI receiver (UI fixture)', platformEndpointId: 'test-hdmi', active: true };
    window.desktop = { nativeAudio: { command: async command => {
      if (command.type === 'device-enumerate') return { ok: true, devices: [device] };
      if (command.type === 'direct-probe') return { ok: window.__allowHdmi, error: window.__allowHdmi ? undefined : 'HDMI_ENDPOINT_DISCONNECTED' };
      if (command.type === 'device-capabilities') return { ok: true, availableSampleRates: [44100,48000], availableBufferSizes: [512] };
      return { ok: true, ...device, sampleRate: 48000, bufferSize: 512, bitDepth: 24, activeOutputChannels: [0,1] };
    } }, browser: { setVolume() {}, setOutput: async () => ({ok:true}), setAnalysisConfig() {} },
      setColorTheme() {}, setImmersive() {}, setWindowGlass() {}, setCompact() {}, setClickThrough() {}, setClickThroughBypass() {} };
    usePlayerStore.getState().setUiSetting('animations', false);
    usePlayerStore.getState().setActivePage('devices');
  });
  for (let i = 0; i < 60 && !await evaluate(() => !!document.querySelector('.hdmi-output-policy button')); i++) await pause(100);
  await pause(400);
  await evaluate(() => document.querySelectorAll('.hdmi-output-policy button')[1].click());
  await pause(500);
  assert.equal(await evaluate(() => window.__hdmi.getState().uiSettings.hdmiDirectEnabled), true);
  assert.equal(await evaluate(() => document.querySelector('.native-advanced-settings').closest('fieldset').disabled), true);
  const output = path.resolve(__dirname, '../../release-work');
  win.webContents.invalidate(); await pause(800);
  await fs.writeFile(path.join(output, 'hdmi-ui-dark.png'), (await win.webContents.capturePage()).toPNG());
  await evaluate(() => window.__hdmi.getState().setUiSetting('colorMode', 'light'));
  await pause(300);
  win.webContents.invalidate(); await pause(800);
  await fs.writeFile(path.join(output, 'hdmi-ui-light.png'), (await win.webContents.capturePage()).toPNG());
  await evaluate(() => document.querySelector('.volume-popover-trigger').click()); await pause(200);
  assert.equal(await evaluate(() => !!document.querySelector('.channel-strip-popover .hdmi-output-policy')), true);
  assert.equal(await evaluate(() => !!document.querySelector('.channel-strip-popover [role=slider]')), false);
  await evaluate(() => document.querySelector('.channel-strip-popover header button').click());
  await evaluate(() => document.querySelectorAll('.hdmi-output-policy button')[0].click()); await pause(300);
  assert.equal(await evaluate(() => window.__hdmi.getState().uiSettings.hdmiDirectEnabled), false);
  await evaluate(() => { window.__allowHdmi = false; document.querySelectorAll('.hdmi-output-policy button')[1].click(); }); await pause(300);
  assert.equal(await evaluate(() => window.__hdmi.getState().uiSettings.hdmiDirectEnabled), false);
  assert.equal(await evaluate(() => document.querySelector('.hdmi-output-policy [role=alert]').textContent.includes('HDMI_ENDPOINT_DISCONNECTED')), true);
  assert.equal(await evaluate(() => !!document.querySelector('.hdmi-output-policy [role=status]')), false);
  await evaluate(() => document.querySelector('.native-device-refresh').click()); await pause(300);
  assert.equal(await evaluate(() => !!document.querySelector('.hdmi-output-policy [role=alert]')), false);
  assert.deepEqual(errors, []);
  console.log('PASS: HDMI UI dark/light, enable/normal policy, controls bypassed, popover, unavailable endpoint rejection; mock devices, no audio emitted.');
  win.destroy(); app.quit();
})().catch(error => { console.error(error); app.exit(1); });
