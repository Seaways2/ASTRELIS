import fs from "node:fs";
import path from "node:path";

const directories = ["decoded-audio", "direct-audio"] as const;
export class AudioCacheMaintenance {
  private active = 0;
  private cleaning?: Promise<unknown>;
  private pins = new Map<string, Set<string>>();
  constructor(private root: string) {}
  protect(owner: string, files: string[]) {
    this.pins.set(owner, new Set(files.map(file => path.resolve(file).toLowerCase())));
  }
  async use<T>(operation: () => Promise<T>): Promise<T> {
    while (this.cleaning) await this.cleaning;
    this.active++;
    try { return await operation(); } finally { this.active--; }
  }
  private protected(file: string) {
    return [...this.pins.values()].some(files => files.has(path.resolve(file).toLowerCase()));
  }
  private async entries() {
    const result: { path: string; bytes: number; modified: number; category: string }[] = [];
    for (const category of directories) {
      const directory = path.resolve(this.root, category);
      try {
        const stat = await fs.promises.lstat(directory);
        if (!stat.isDirectory() || stat.isSymbolicLink()) continue;
        if (path.resolve(await fs.promises.realpath(directory)).toLowerCase() !== directory.toLowerCase()) continue;
        for (const entry of await fs.promises.readdir(directory, { withFileTypes: true })) {
          // Only files generated by these two caches; never recurse or follow links.
          if (!entry.isFile() || !/^(?:[a-f0-9]{40}\.wav|[a-f0-9]{64}\.raw|[a-f0-9]{40}(?:\.wav)?\.[a-f0-9-]{36}\.tmp\.wav|[a-f0-9]{64}\.raw\.[a-f0-9-]{36}\.tmp)$/.test(entry.name)) continue;
          const file = path.join(directory, entry.name);
          const detail = await fs.promises.lstat(file);
          if (detail.isFile() && !detail.isSymbolicLink()) result.push({ path: file, bytes: detail.size, modified: detail.mtimeMs, category });
        }
      } catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
    }
    return result;
  }
  async inspect() {
    const entries = await this.entries();
    return { path: this.root, bytes: entries.reduce((sum, file) => sum + file.bytes, 0),
      protectedBytes: entries.filter(file => this.protected(file.path)).reduce((sum, file) => sum + file.bytes, 0),
      decodedBytes: entries.filter(file => file.category === "decoded-audio").reduce((sum, file) => sum + file.bytes, 0),
      directBytes: entries.filter(file => file.category === "direct-audio").reduce((sum, file) => sum + file.bytes, 0), busy: this.active > 0 || !!this.cleaning };
  }
  async clear() {
    if (this.active || this.cleaning) return { ok: false, error: "音源正在准备，请稍后重试 / Audio preparation is busy" };
    // Set the barrier before any asynchronous filesystem work.
    const job = this.removeUnused();
    this.cleaning = job;
    try { return await job; } finally { this.cleaning = undefined; }
  }
  private async removeUnused() {
    let removedBytes = 0, skippedBytes = 0, failedFiles = 0;
    for (const file of await this.entries()) {
      if (this.protected(file.path)) { skippedBytes += file.bytes; continue; }
      // Recheck the canonical parent and leaf immediately before unlinking.
      const parent = path.dirname(file.path);
      if (path.resolve(await fs.promises.realpath(parent)).toLowerCase() !== parent.toLowerCase()) { failedFiles++; continue; }
      const detail = await fs.promises.lstat(file.path).catch(() => undefined);
      if (!detail || !detail.isFile() || detail.isSymbolicLink() || this.protected(file.path)) { skippedBytes += file.bytes; continue; }
      try { await fs.promises.unlink(file.path); removedBytes += file.bytes; }
      catch { failedFiles++; }
    }
    return { ok: true, removedBytes, skippedBytes, failedFiles };
  }
}
