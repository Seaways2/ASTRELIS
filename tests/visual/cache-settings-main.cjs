const {app,BrowserWindow,ipcMain} = require('electron');
const fs=require('node:fs'), path=require('node:path'), assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..');
const profile=process.env.ASTRELIS_RESOURCE_TEST_PROFILE;
if(!profile || path.dirname(profile)!==path.join(root,'release-work')) throw Error('Isolated profile required');
delete process.env.VITE_DEV_SERVER_URL;
app.setAppPath(root); app.setPath('userData',profile); app.setPath('sessionData',profile);
const audio=path.join(profile,'decoded-audio'); fs.mkdirSync(audio,{recursive:true});
const unused=path.join(audio,'a'.repeat(40)+'.wav'), active=path.join(audio,'b'.repeat(40)+'.wav');
fs.writeFileSync(unused,Buffer.alloc(1024)); fs.writeFileSync(active,Buffer.alloc(2048));
const original=path.join(profile,'original-music.wav'); fs.writeFileSync(original,'preserved');
const pause=ms=>new Promise(r=>setTimeout(r,ms));
const timeout=setTimeout(()=>app.exit(1),60000);
require('../../dist-electron/main.js');
(async()=>{
  await app.whenReady(); let win;
  while(!(win=BrowserWindow.getAllWindows()[0]) || win.webContents.isLoading()) await pause(100);
  const js=script=>win.webContents.executeJavaScript(script,true);
  while(!await js('Boolean(document.querySelector(".titlebar"))')) await pause(100);
  const data=await js('window.desktop.cache.inspect()');
  assert.equal(data.bytes,3072);
  await js(`window.desktop.cache.protect(${JSON.stringify([active])})`);
  await js(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent.includes('系统设置') || b.title === '系统设置')?.click()`);
  for(let i=0;i<40 && !await js('Boolean(document.querySelector(".cache-settings"))');i++) await pause(100);
  assert.ok(await js('Boolean(document.querySelector(".cache-settings"))'),'Cache settings rendered');
  await js('document.querySelector(".cache-settings").scrollIntoView({block:"center"})'); await pause(200);
  await js('document.querySelectorAll(".cache-settings .cache-actions button")[1].click()');
  await pause(100);
  assert.ok(await js('Boolean(document.querySelector(".cache-confirm"))'),'Clear requires review');
  await js('document.querySelector(".cache-confirm button").click()'); await pause(300);
  assert.equal(fs.existsSync(unused),false); assert.ok(fs.existsSync(active)); assert.ok(fs.existsSync(original));
  assert.match(await js('document.querySelector(".cache-settings").textContent'),/已释放/);
  win.minimize(); await pause(200);
  assert.ok(await js('document.querySelector(".app-shell").classList.contains("visuals-suspended")'));
  win.restore(); await pause(250);
  assert.equal(await js('document.querySelector(".app-shell").classList.contains("visuals-suspended")'),false);
  await js('document.querySelector(".cache-settings").scrollIntoView({block:"center"})');
  const image=await win.webContents.capturePage(); fs.writeFileSync(path.join(profile,'cache-settings.png'),image.toPNG());
  const dts=path.join(profile,'preload-test.dts');
  require('node:child_process').execFileSync(path.join(root,'ffmpeg/ffmpeg.exe'),['-v','error','-y','-f','lavfi','-i','anullsrc=r=48000:cl=stereo','-t','0.3','-c:a','dca','-strict','-2','-b:a','768k',dts],{windowsHide:true});
  ipcMain.emit('library:authorize-dropped-file',{sender:win.webContents,senderFrame:win.webContents.mainFrame},dts);
  const direct=await js(`window.desktop.library.prefetch(${JSON.stringify(dts)},true)`);
  assert.equal(direct.ok,true,JSON.stringify(direct));
  const decoded=await js(`window.desktop.library.prepare(${JSON.stringify(dts)})`);
  assert.equal(decoded.ok,true);
  const oldModified=fs.statSync(decoded.path).mtimeMs;
  const again=await js(`window.desktop.library.prefetch(${JSON.stringify(dts)},false)`);
  assert.equal(again.ok,true); assert.equal(fs.statSync(decoded.path).mtimeMs,oldModified,'Preloaded analysis reused for normal playback');
  const usage=await js('window.desktop.cache.inspect()'); assert.ok(usage.bytes>3072);
  console.log('Real DTS prefetch and normal decoded-cache reuse: PASS');
  console.log('Cache UI, IPC, isolated cleanup, active file protection, minimize/restore: PASS');
  clearTimeout(timeout); app.exit(0);
})().catch(error=>{console.error(error);clearTimeout(timeout);app.exit(1);});
